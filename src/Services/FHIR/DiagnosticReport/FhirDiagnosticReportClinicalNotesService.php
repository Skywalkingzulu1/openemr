class FhirDiagnosticReportClinicalNotesService extends FhirServiceBase implements IResourceUSCIGProfileService, IPatientCompartmentResourceService
{
    use FhirServiceBaseEmptyTrait;
    use PatientSearchTrait;
    use VersionedProfileTrait;

    const USCGI_PROFILE_URI = 'http://hl7.org/fhir/us/core/StructureDefinition/us-core-diagnosticreport-note';

    /**
     * @var ClinicalNotesService
     */
    private $service;

    public function __construct($fhirApiURL = null)
    {
        parent::__construct($fhirApiURL);
        $this->service = new ClinicalNotesService();
    }

    public function setSession(SessionInterface $session): void
    {
        parent::setSession($session); // TODO: Change the autogenerated stub
        $this->service->setSession($session);
    }

    /**
     * Returns an array mapping FHIR Resource search parameters to DCL search parameters
     */
    protected function loadSearchParameters(): array
    {
        return  [
            'patient' => $this->getPatientContextSearchField(),
            'code' => new FhirSearchParameterDefinition('code', SearchFieldType::TOKEN, ['code']),
            'category' => new FhirSearchParameterDefinition('category', SearchFieldType::TOKEN, ['category_code']),
            'date' => new FhirSearchParameterDefinition('date', SearchFieldType::DATETIME, ['date']),
            '_id' => new FhirSearchParameterDefinition('_id', SearchFieldType::TOKEN, [new ServiceField('uuid', ServiceField::TYPE_UUID)]),
            '_lastUpdated' => $this->getLastModifiedSearchField(),
        ];
    }

    public function getLastModifiedSearchField(): ?FhirSearchParameterDefinition
    {
        return new FhirSearchParameterDefinition('_lastUpdated', SearchFieldType::DATETIME, ['last_updated']);
    }

    public function supportsCategory($category): bool
    {
        $loincCategory = "LOINC:" . $category;
        $listService = new ListService();
        $options = $listService->getOptionsByListName('Clinical_Note_Category', ['notes' => $loincCategory]);
        return !empty($options);
    }


    public function supportsCode($code)
    {
        return $this->service->isValidClinicalNoteCode($code);
    }

    public function parseDCLRecord($dataRecord = [], $encode = false): FHIRDiagnosticReport
    {
        $report = new FHIRDiagnosticReport();
        $this->populateMeta($report, $dataRecord);

        $id = new FHIRId();
        $id->setValue($dataRecord['uuid']);
        $report->setId($id);

        if (!empty($dataRecord['date'])) {
            $date = UtilsService::getLocalDateAsUTC($dataRecord['date']);
            $report->setEffectiveDateTime(new FHIRDateTime($date));
            $report->setIssued(new FHIRInstant($date));
        } else {
            $report->setDate(UtilsService::createDataMissingExtension());
        }

        if (!empty($dataRecord['euuid'])) {
            $report->setEncounter(UtilsService::createRelativeReference('Encounter', $dataRecord['euuid']));
        }

        $fhirOrganizationService = new FhirOrganizationService();

        if (!empty($dataRecord['user_uuid'])) {
            if (!empty($dataRecord['npi'])) {
                $responsibleParty = UtilsService::createRelativeReference('Practitioner', $dataRecord['user_uuid']);
            } else {
                $responsibleParty = $fhirOrganizationService->getOrganizationReferenceForUser($dataRecord['user_uuid']);
            }
        } else {
            $responsibleParty = $fhirOrganizationService->getPrimaryBusinessEntityReference();
        }
        if (!empty($responsibleParty)) {
            $report->addPerformer($responsibleParty);
            // we don't separate interpreter from responsible party in clinical notes so they'll be the same
            $report->addResultsInterpreter($responsibleParty);
        }

        // version 7.0.0 has a results field which is a link to a media attachment which would be the DICOM image or some other imaging png,jpg, etc.
        if (!empty($dataRecord['documents'])) {
            foreach ($dataRecord['documents'] as $document) {
                $media = new FhirDiagnosticReportMedia();
                $media->setLink(UtilsService::createRelativeReference('Media', $document['uuid']));
                $report->addMedia($media);
            }
        }

        if (!empty($dataRecord['linked_results'])) {
            foreach ($dataRecord['linked_results'] as $linkedResult) {
                $report->addResult(UtilsService::createRelativeReference('Observation', $linkedResult['uuid']));
            }
        }


        // populate our clinical narrative notes
        if (!empty($dataRecord['description'])) {
            $attachment = new FHIRAttachment();
            $attachment->setContentType("text/plain");
            $attachment->setData(base64_encode((string) $dataRecord['description']));
            $report->addPresentedForm($attachment);
        } else {
            // need to support data missing if its not there.
            $report->addPresentedForm(UtilsService::createDataMissingExtension());
        }

        if (!empty($dataRecord['puuid'])) {
            $report->setSubject(UtilsService::createRelativeReference('Patient', $dataRecord['puuid']));
        }

        $codeTypesService = new CodeTypesService();
        $codeParts = $codeTypesService->parseCode($dataRecord['category_code']);
        $code = $codeParts['code'];

        $category = UtilsService::createCodeableConcept([
            $code => [
                'code' => $code
                ,'description' => $dataRecord['category_title']
                ,'system' => $codeTypesService->getSystemForCodeType($codeParts['code_type'])
            ]
        ], FhirCodeSystemConstants::LOINC); // we default to LOINC if we don't have a valid type

        $report->addCategory($category);

        if (!empty($dataRecord['status'])) {
            $report->setStatus($dataRecord['status']);
        } else {
            $report->setStatus('final');
        }

        if (!empty($dataRecord['code'])) {
            $code = UtilsService::createCodeableConcept($dataRecord['code'], FhirCodeSystemConstants::LOINC, $dataRecord['codetext']);
            $report->setCode($code);
        } else {
            $report->setCode(UtilsService::createNullFlavorUnknownCodeableConcept());
        }

        return $report;
    }

    /**
     * Searches for DCL records using DCL search parameters
     * @param array<string, ISearchField> $DCLSearchParameters DCL search fields
     * @return ProcessingResult DCL records
     */
    protected function searchForDCLRecords($DCLSearchParameters): ProcessingResult
    {
        if (isset($DCLSearchParameters['code']) && $DCLSearchParameters['code'] instanceof TokenSearchField) {
            $DCLSearchParameters['code']->transformValues($this->addLOINCPrefix(...));
        }

        if (isset($DCLSearchParameters['category_code']) && $DCLSearchParameters['category_code'] instanceof TokenSearchField) {
            $DCLSearchParameters['category_code']->transformValues($this->addLOINCPrefix(...));
        } else {
            // we need to make sure we only include things with a category code in our clinical notes
            $DCLSearchParameters['category_code'] = new TokenSearchField('category_code', [new TokenSearchValue(false)]);
            $DCLSearchParameters['category_code']->setModifier(SearchModifier::MISSING);
        }
        $result = $this->service->search($DCLSearchParameters);
        return $result;
    }

    public function addLOINCPrefix(TokenSearchValue $val)
    {
        // TODO: @adunsulag I don't like this, is there a way we can mark the code system we are using that will prefix the value
        // already?
        $val->setCode("LOINC:" . $val->getCode());
        return $val;
    }

    /**
     * Creates the Provenance resource  for the equivalent FHIR Resource
     *
     * @param $dataRecord The source DCL data record
     * @param $encode Indicates if the returned resource is encoded into a string. Defaults to True.
     * @return the FHIR Resource. Returned format is defined using $encode parameter.
     */
    public function createProvenanceResource($dataRecord, $encode = false)
    {
        if (!($dataRecord instanceof FHIRDiagnosticReport)) {
            throw new \BadMethodCallException("Data record should be correct instance class");
        }
        $fhirProvenanceService = new FhirProvenanceService();
        $performer = null;
        if (!empty($dataRecord->getPerformer())) {
            $performer = current($dataRecord->getPerformer());
        }
        $fhirProvenance = $fhirProvenanceService->createProvenanceForDomainResource($dataRecord, $performer);
        if ($encode) {
            return json_encode($fhirProvenance);
        } else {
            return $fhirProvenance;
        }
    }


    protected function populateMeta(FHIRDiagnosticReport $report, array $dataRecordReport): void
    {
        $fhirMeta = new FHIRMeta();
        $fhirMeta->setVersionId('1');
        if (!empty($dataRecordReport['last_updated'])) {
            $fhirMeta->setLastUpdated(UtilsService::getLocalDateAsUTC($dataRecordReport['last_updated']));
        } else {
            $fhirMeta->setLastUpdated(UtilsService::getDateFormattedAsUTC());
        }
        // Set profile (required, mustSupport)
        $this->addProfilesToMeta($fhirMeta, $dataRecordReport);
        $report->setMeta($fhirMeta);
    }

    /**
     * @param FHIRMeta $meta
     * @param array $dataRecord
     * @return void
     */
    protected function addProfilesToMeta(FHIRMeta $fhirMeta, array $dataRecordReport): void
    {
        $profiles = $this->getProfileForVersions(self::USCGI_PROFILE_URI, $this->getSupportedVersions());
        foreach ($profiles as $profileUrl) {
            $profile = new FHIRCanonical();
            $profile->setValue($profileUrl);
            $fhirMeta->addProfile($profile);
        }
    }

    public function getProfileURIs(): array
    {
        return $this->getProfileForVersions(self::USCGI_PROFILE_URI, $this->getSupportedVersions());
    }
}
